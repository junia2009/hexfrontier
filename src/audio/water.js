export const WATER_KINDS = Object.keys(WATER);

// 泡が満たすべき条件。
//   minN/maxN 少なすぎると「ピチョン」が数個鳴るだけ、多すぎると重なって
//             ただの雑音になる。実測で、聞き分けられる粒は 8〜11 個で
//             頭打ち ── 24 個を超えて増やしても一切増えなかった。
//   minHz     泡の高さは大きさで決まる(ミンナールト: f ≒ 3.28/半径[m])。
//             150Hz は半径 2.2cm ── 泡としてありうる大きさの上限あたり。
//             これより下は物として泡ではなく、ただの低い音程になる。
//             しかも低い泡は寿命が長いぶん、音程が上がるのが「ブォン」と
//             いう滑りとして聞こえてしまう(最初の版がまさにそれだった)。
//   maxLoHz   逆に、いちばん大きい泡がここより高いと軽い音しか出ない。
export const BUBBLE_LIMITS = { minN: 4, maxN: 40, minHz: 150, maxLoHz: 1400 };

// 層どうしが同じ帯域で喧嘩しないよう、一撃は泡よりはっきり上に置く。
export const BAND_GAP = 1.4;

// 地面と違って水は動きで変わらないので、倍率は大きさだけ(scale)。
export function waterSound(kind = 'dive', scale = 1) {
  const w = WATER[kind] ?? WATER.dive;
  const k = Number.isFinite(scale) ? Math.max(0, Math.min(2, scale)) : 1;
  const lay = (src) => ({ ...src, gain: +(src.gain * k).toFixed(4) });
  return { impact: lay(w.impact), cavity: lay(w.cavity), bubbles: lay(w.bubbles) };
}

// 水の音。足音(footsteps.js)と同じ作り(決めごとの表 + sfx.js の薄いボイス)。
//
// **狙うのは「本物らしさ」ではなく「効果音としての正しさ」。**
// ここは本物に寄せようとして何度も外した。物理をどれだけ正しくしても、
// 効果音としては別の話だった ── 実物の飛沫はほとんど雑音の塊で、
// 短い一発として鳴らすと「何の音か分からない濁り」にしかならない。
// 効果音に要るのは、**0.1 秒で「水だ」と分かること**。
//
// 水の合図としていちばん強いのは「ポチャン」の**上がる音程**。
// 漫画の水音が必ず上がるのはこれで、人はこの形を水として覚えている。
// だから正しく作るのではなく、**この形をはっきり出す**。
//
// 層は3つだけ:
//   splash  … 水面が割れる「シャッ」。明るい雑音。頭の数十 ms。
//   ploop   … **上がる音程。これが水の正体**。短く、和音に馴染む高さで。
//   sparkle … 跳ねた滴。高く短い粒をいくつか。尾のきらめき。
//
// **守ること(どれも一度破って怒られた):**
//   - **低い音を下へ滑らせない。** ローパスした雑音を低いほうへ滑らせるのは
//     屁の音の作りかたそのもので、「うんちしてる感じ」と言われた。
//   - **音程は上げる。下げない。** 下がる音程は水ではなく体の音になる。
//   - **低くしすぎない。** 下品な帯に入る。いちばん大きい着水でも G3。
//   - **層を重ねすぎない。** 帯域と時刻を分ける。重なると互いを埋めて
//     「複雑なのに何も聞こえない」濁りになる。
//   - **短く。** 効果音は居座らない。いちばん長い層でも 0.45 秒。
//
// 音程は BGM と同じ D ドリアに乗せる(効果音全体の決まり)。
// 規模は「大きいほど低く、長く、粒が多い」で作り分ける。


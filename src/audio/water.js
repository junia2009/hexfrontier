// 水の音。足音(footsteps.js)と同じ考えで、決めごとだけをここに置く。
// 実際に鳴らすのは sfx.js。Web Audio の無い node --test でも検査できる。
//
// **層は3つだけ。それぞれ別の帯域・別の時間に置く。**
//   impact  … 水面が割れる一撃。明るく、頭の 40ms だけ。
//   cavity  … 体が押しのけた水の重み。低いほうだけ、**短く一撃で**。
//   bubbles … 泡。中くらいの高さで、まばらに。**尾のほうで鳴る。**
//
// **低い音を下へ滑らせない。これは何度やっても屁の音になる。**
// 「水は沈むのだから帯域も下げる」と考えて、低い唸りを 520→130Hz へ
// 200ms かけて滑らせていた。ローパスした雑音を低いほうへ滑らせるのは
// **屁の音の作りかたそのもの**で、しかもそれが全層でいちばん大きかった。
// 実際「うんちしてる感じ」と言われ、そのうえ帯域の分析が「低音が
// 足りない」と出るたびに、こちらはそれを大きくし続けていた。
// (物理的にも逆だった。空洞はただの大きな泡なので、縮むにつれて
//  音は**上がる**。下がりはしない。)
// いまは滑らせず、短い一撃として置く。低い成分は「重み」であって
// 「動き」ではない ── 動かした瞬間に体の音になる。
//
// 帯域と時刻を分けるのが肝。ここが重なると、層どうしが同じところで
// 鳴って互いを埋め、音が「濁って何も聞こえない」状態になる
// (実際そうなって「複雑にしすぎて音が喧嘩している」と言われた。
//  そのとき泡は 520〜7000Hz で、他の2層を丸ごと覆っていた)。
//
// **泡は増やすほど水らしくなる、ではない。** 泡はランダムな位相の
// 正弦波なので、たくさん重ねると中心極限定理でただの雑音に収束する
// ── つまり増やすほど「フィルタした雑音」に近づく。実測でも、
// はっきり聞き分けられる粒の数は 8〜11 個で頭打ちになり、
// 泡を 24 個から 280 個に増やしても**まったく増えなかった**。
// 増やしたぶんは濁りと計算量になるだけなので、20 個前後に留める。
//
// 泡ひとつの物理(これは式どおりに作る):
//   高さ … ミンナールト f ≒ 3.28/半径[m](半径 1cm で 328Hz)
//   減衰 … f·r が一定なので Q は大きさによらず 17 前後。τ = Q/(πf)
//   大きさ … 放射する音は半径に比例、つまり振幅 ∝ 1/f
//   音程 … 縮みながら鳴るので上がる(「ポチャン」の「ャン」)


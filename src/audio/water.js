export const WATER_KINDS = Object.keys(WATER);

// 効果音として守る線。**どれも破って怒られた結果**なので、理由ごと残す。
//   minPloopMidi  これより低い音程は、上がっていても下品な帯に入る。
//                 55 = G3(196Hz)。着水でもここを下回らない。
//   maxDur        効果音は居座らない。いちばん長い層でもこれ以下。
//   maxSparkleN   粒は増やすほど雑音に収束して、かえって水から遠ざかる
//                 (実測で、聞き分けられる粒は 8〜11 個で頭打ちだった)。
//   bandGap       層どうしの帯域をこれだけ離す。近いと互いを埋める。
export const FX_LIMITS = {
  minPloopMidi: 55, maxDur: 0.45, maxSparkleN: 12, bandGap: 1.4,
};

// D ドリアの音度(sfx.js の D と同じ並び)。効果音は全部この上に乗せる。
export const SCALE_PCS = [2, 4, 5, 7, 9, 11, 0];

// 地面と違って水は動きで変わらないので、倍率は大きさだけ(scale)。
export function waterSound(kind = 'dive', scale = 1) {
  const w = WATER[kind] ?? WATER.dive;
  const k = Number.isFinite(scale) ? Math.max(0, Math.min(2, scale)) : 1;
  const lay = (src) => ({ ...src, gain: +(src.gain * k).toFixed(4) });
  return { splash: lay(w.splash), ploop: lay(w.ploop), sparkle: lay(w.sparkle) };
}
